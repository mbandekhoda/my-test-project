# برنامه‌ای برای دریافت دو عدد از کاربر و نمایش جمع آن‌ها

try:
    # دریافت عدد اول از کاربر
    num1 = float(input("عدد اول را وارد کنید: "))
    
    # دریافت عدد دوم از کاربر
    num2 = float(input("عدد دوم را وارد کنید: "))
    
    # محاسبه جمع
    result = num1 + num2
    
    # نمایش نتیجه
    print(f"جمع {num1} و {num2} برابر است با: {result}")

except ValueError:
    print("خطا: لطفاً فقط اعداد معتبر وارد کنید.")
